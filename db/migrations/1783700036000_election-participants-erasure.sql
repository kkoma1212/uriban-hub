/*
 * 왜 이 권한이 필요한가 — 탈퇴하면 선거 참여 기록도 지워야 한다(2026-08-22 Hex 승인).
 *
 * 개인정보처리방침 §3.4 는 계정을 지우면 "해당 학생의 행이 삭제된다"고 약속한다.
 * 그런데 선거 참여 기록에는 앱 계정의 DELETE 권한이 없어서 지울 수가 없었다 —
 * 탈퇴한 뒤에도 "이 학생은 투표했다"가 남고, 후보였다면 이름·학생번호 사본까지 남았다
 * (2026-08-22 감사 RED/BLUE-03, P1).
 *
 * ⚠️ **옛 주석을 보고 이 권한을 되돌리지 말 것.** 원래 이렇게 적혀 있었다:
 *   "참여 기록은 지울 수 없다. 지울 수 있으면 다시 투표하게 만들 수 있다."
 * 그 우려는 **계정이 살아 있을 때**의 것이다. 지우는 경로는 계정 삭제·반 떠나기·
 * 내보내기 셋뿐이고, 그 뒤에는 그 계정으로 로그인 자체가 안 되므로 재투표가 성립하지
 * 않는다. 앱이 임의로 참여 기록을 지우는 길은 여전히 열려 있지 않다 — 서비스 코드의
 * 삭제 호출은 저 세 경로에만 있다.
 *
 * **개표 결과는 바뀌지 않는다.** 득표 수는 `election_tallies` 에 따로 세어 두고
 * 참여 기록과 짝지어 두지 않았다(이 표의 설계 목적이 그것이다). 참여 행이 사라져도
 * 집계는 그대로이고, 오히려 "누가 참여했는지"가 지워져 무기명성에는 도움이 된다.
 *
 * **후보 기록은 지우지 않고 이름만 지운다.** 개표 결과(`election_tallies`)가 후보를
 * `ON DELETE RESTRICT` 로 참조하므로, 후보 행을 지우면 삭제가 막히거나 **지난 선거의
 * 득표 수가 함께 사라진다.** 남겨야 하는 것은 "몇 표였나"이고 지워야 하는 것은
 * "누구였나"다. 그래서 표시명·학생번호만 비우며, 그러려면 UPDATE 권한이 필요하다
 * (지금은 SELECT·INSERT·DELETE 만 있다).
 *
 * 당번 배정(`duty_assignments`)은 참조하는 표가 없어 DELETE 로 지운다 — 이미 권한이 있다.
 */
GRANT DELETE ON election_participants TO classhub_app;
GRANT UPDATE ON election_candidates TO classhub_app;

