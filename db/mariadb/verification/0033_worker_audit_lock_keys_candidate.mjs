import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL, URL } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const readRepository = (path) => readFileSync(resolve(root, path), "utf8");
export const workerAuditLockKeysFile = "db/mariadb/migrations/0033_worker_audit_lock_keys.sql";

/** Source-only operational table candidate, outside the 65 product-table manifest. */
export function buildWorkerAuditLockKeysCandidate() {
  return [
    "-- T-HUB-64: dynamic worker audit scope locks; REVIEW CANDIDATE ONLY.",
    "-- ISOLATED SYNTHETIC QA ONLY. DO NOT APPLY TO A SHARED OR PRODUCTION DATABASE.",
    "-- runtimeActivationApplied=false; operational table outside the 65 product tables.",
    "-- Generated by db/mariadb/verification/0033_worker_audit_lock_keys_candidate.mjs --write.",
    "-- Runtime requires SELECT and INSERT only, with a separately reviewed exact worker ACL.",
    "-- Existing runtime catalog, manifests, mounts and 0032 static registry are unchanged.",
    "-- Store only a domain-separated SHA-256 digest; no raw identity, event payload or user/IP FK.",
    "-- prepare commits registrations before business transactions; rows survive business rollback.",
    "-- Distinct scopes accumulate indefinitely. No production TTL/DELETE/retention is implemented.",
    "-- QA cleanup must stop all workers/pools before restoring its initial registration set.",
    "-- This is worker scope coordination, not full PG hashtext/direct-bigint key-space emulation.",
    "",
    "CREATE TABLE worker_security_audit_lock_keys (",
    "  lock_digest BINARY(32) NOT NULL,",
    "  PRIMARY KEY (lock_digest)",
    ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;",
    "",
  ].join("\n");
}
export function verifyWorkerAuditLockKeysCandidate(read = readRepository) {
  const migrationSql = buildWorkerAuditLockKeysCandidate();
  assert.equal(
    read(workerAuditLockKeysFile).replaceAll("\r\n", "\n"),
    migrationSql,
    "0033 operational table differs from the reviewed digest-only definition",
  );
  return {
    status: "worker_audit_lock_keys_candidate_pass",
    operationalTables: 1,
    initialRegistrations: 0,
    runtimePrivilegesRequired: ["INSERT", "SELECT"],
    registrationsAccumulate: true,
    productionCleanupImplemented: false,
    runtimeActivationApplied: false,
    realMariaDbVerified: false,
    migrationSha256: createHash("sha256").update(migrationSql).digest("hex"),
  };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  assert.ok(
    args.length <= 1 && [undefined, "--check", "--write"].includes(args[0]),
    "only --check or explicit --write is supported",
  );
  if (args[0] === "--write")
    writeFileSync(
      resolve(root, workerAuditLockKeysFile),
      buildWorkerAuditLockKeysCandidate(),
      "utf8",
    );
  process.stdout.write(JSON.stringify(verifyWorkerAuditLockKeysCandidate()) + "\n");
}
