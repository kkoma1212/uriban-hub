import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL, URL } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const readRepository = (path) => readFileSync(resolve(root, path), "utf8");
const hash = (text) => createHash("sha256").update(text).digest("hex");
const normalize = (text) => text.replaceAll("\r\n", "\n");
export const classAccessApprovalFiles = {
  migration: "db/mariadb/migrations/0030_class_access_approval.sql",
  owner: "db/mariadb/permissions/0030_class_access_approval_owner.sql",
};
export const classAccessApprovalSources = [
  "db/mariadb/migrations/0002_class_transition_lifecycle_routines.sql",
  "db/mariadb/migrations/0002_class_transition_membership_routines.sql",
  "db/mariadb/permissions/0002_class_membership_helper_grants.sql",
  "db/mariadb/migrations/0021_admin_signup_approvals.sql",
  "apps/api/src/auth/account-access-policy.ts",
];
const names = ["create_class_with_teacher_and_invite", "request_class_membership"];
const replacements = [
  ["CREATE DEFINER", "CREATE OR REPLACE DEFINER"],
  [
    "  DECLARE locked_user_verified_at DATETIME(6);",
    "  DECLARE locked_user_verified_at DATETIME(6);\n  DECLARE locked_user_signup_approved_at DATETIME(6);",
  ],
  [
    "    SELECT id, is_active, deleted_at, email_verified_at\n",
    "    SELECT id, is_active, deleted_at, email_verified_at, signup_approved_at\n",
  ],
  [
    "    INTO locked_user_id, locked_user_active, locked_user_deleted_at, locked_user_verified_at\n",
    "    INTO locked_user_id, locked_user_active, locked_user_deleted_at, locked_user_verified_at, locked_user_signup_approved_at\n",
  ],
  [
    "  IF locked_user_verified_at IS NULL THEN",
    "  IF locked_user_verified_at IS NULL AND locked_user_signup_approved_at IS NULL THEN",
  ],
];

function replaceOnce(text, before, after) {
  const parts = text.split(before);
  assert.equal(parts.length, 2, "approval candidate source anchor changed or is ambiguous");
  return parts.join(after);
}
function extractRoutine(source, name, replaced = false) {
  const prefix = `CREATE${replaced ? " OR REPLACE" : ""} DEFINER = 'classhub_routine'@'%' PROCEDURE ${name}(`;
  const parts = source.split(prefix);
  assert.equal(parts.length, 2, `expected exactly one routine definition: ${name}`);
  const end = parts[1].indexOf("\nEND//");
  assert.ok(end >= 0, `missing routine terminator: ${name}`);
  return prefix + parts[1].slice(0, end + "\nEND//".length);
}

/** File-only review candidate. This function never connects to a database. */
export function buildClassAccessApprovalCandidate(read = readRepository) {
  const sources = Object.fromEntries(classAccessApprovalSources.map((path) => [path, read(path)]));
  const normalized = Object.fromEntries(
    Object.entries(sources).map(([path, text]) => [path, normalize(text)]),
  );
  assert.ok(
    normalized[classAccessApprovalSources[2]].includes(
      "GRANT SELECT (id, is_active, deleted_at, email_verified_at)\n" +
        "  ON classhub_mariadb_phase1_dev.users\n  TO 'classhub_routine'@'%';",
    ),
    "original owner read envelope changed",
  );
  assert.ok(
    normalized[classAccessApprovalSources[3]].includes(
      "ALTER TABLE users ADD COLUMN signup_approved_at DATETIME(6);",
    ),
    "phase 0021 signup approval column changed",
  );
  assert.match(
    normalized[classAccessApprovalSources[4]],
    /return \(\s*account\.email_verified_at !== null \|\|\s*\(account\.signup_approved_at !== null && account\.signup_approved_at !== undefined\)\s*\);/u,
    "current application account approval policy changed",
  );
  const originals = names.map((name, index) =>
    extractRoutine(normalized[classAccessApprovalSources[index]], name),
  );
  const routines = originals.map((original) => {
    const candidate = replacements.reduce(
      (text, [before, after]) => replaceOnce(text, before, after),
      original,
    );
    const restored = [...replacements]
      .reverse()
      .reduce((text, [before, after]) => replaceOnce(text, after, before), candidate);
    assert.equal(restored, original, "candidate changed SQL outside the exact approval decision");
    return candidate;
  });
  const migrationSql = [
    "-- T-HUB-64: class access approval follow-up; REVIEW CANDIDATE ONLY.",
    "-- ISOLATED SYNTHETIC QA ONLY. DO NOT APPLY TO A SHARED OR PRODUCTION DATABASE.",
    "-- runtimeActivationApplied=false; parser/semantics/ACL verification is required separately.",
    "-- Generated by db/mariadb/verification/0030_class_access_approval_candidate.mjs --write.",
    "-- Requires phase 0021 users.signup_approved_at and the separate 0030 owner SELECT grant.",
    "-- Preserve the original routine sql_mode, parameter types and collation when replacing.",
    "-- Only these two definitions change; original phase 0002 files remain unchanged.",
    "-- Both approval timestamps are read under the existing users FOR UPDATE lock.",
    "-- Authentication, authorization, audit and idempotency remain caller-owned.",
    "-- Existing error numbers/messages remain unchanged; neither email status nor data is rewritten.",
    ...names.map((name, index) => `-- Original ${name} SHA-256: ${hash(originals[index])}`),
    "",
    "SET time_zone = '+00:00';",
    "SET NAMES utf8mb4 COLLATE utf8mb4_bin;",
    "",
    "DELIMITER //",
    "",
    routines.join("\n\n"),
    "",
    "DELIMITER ;",
    "",
  ].join("\n");
  const ownerSql = [
    "-- T-HUB-64: class access approval owner read delta; REVIEW CANDIDATE ONLY.",
    "-- ISOLATED SYNTHETIC QA ONLY. DO NOT APPLY TO A SHARED OR PRODUCTION DATABASE.",
    "-- runtimeActivationApplied=false; no runtime account grants are added.",
    "-- Generated by db/mariadb/verification/0030_class_access_approval_candidate.mjs --write.",
    "-- Requires phase 0021. Apply before replacing the two class access routines.",
    "-- The locked routine owner receives exactly one additional read column, with no DML.",
    "GRANT SELECT (signup_approved_at)",
    "  ON classhub_mariadb_phase1_dev.users",
    "  TO 'classhub_routine'@'%';",
    "",
  ].join("\n");
  for (const text of [migrationSql, ownerSql])
    assert.ok(text.split("\n").length <= 800, "generated SQL exceeds 800 lines");
  return {
    migrationSql,
    ownerSql,
    routines: [...names],
    sourceHashes: Object.fromEntries(
      Object.entries(sources).map(([path, text]) => [path, hash(text)]),
    ),
    runtimeActivationApplied: false,
  };
}

export function verifyClassAccessApprovalCandidate(migrationSql, ownerSql, read = readRepository) {
  const expected = buildClassAccessApprovalCandidate(read);
  assert.equal(
    normalize(migrationSql),
    expected.migrationSql,
    "class access routine candidate drift",
  );
  assert.equal(normalize(ownerSql), expected.ownerSql, "class access owner grant candidate drift");
  for (let index = 0; index < names.length; index++) {
    const candidate = extractRoutine(normalize(migrationSql), names[index], true);
    const restored = [...replacements]
      .reverse()
      .reduce((text, [before, after]) => replaceOnce(text, after, before), candidate);
    assert.equal(
      restored,
      extractRoutine(normalize(read(classAccessApprovalSources[index])), names[index]),
    );
  }
  return expected;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  assert.ok(
    process.argv.length === 2 ||
      (process.argv.length === 3 && ["--check", "--write"].includes(process.argv[2])),
    "only --check or --write is accepted",
  );
  const candidate = buildClassAccessApprovalCandidate();
  if (process.argv[2] === "--write") {
    writeFileSync(resolve(root, classAccessApprovalFiles.migration), candidate.migrationSql);
    writeFileSync(resolve(root, classAccessApprovalFiles.owner), candidate.ownerSql);
  }
  verifyClassAccessApprovalCandidate(
    readRepository(classAccessApprovalFiles.migration),
    readRepository(classAccessApprovalFiles.owner),
  );
  process.stdout.write(
    JSON.stringify({
      status: "class_access_approval_candidate_pass",
      routines: candidate.routines,
      additionalOwnerReadColumns: 1,
      additionalRuntimeGrants: 0,
      runtimeActivationApplied: false,
      sourceHashes: candidate.sourceHashes,
    }) + "\n",
  );
}
