import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL, URL } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const readRepository = (path) => readFileSync(resolve(root, path), "utf8");
export const transactionLockKeysFiles = {
  migration: "db/mariadb/migrations/0032_transaction_lock_keys.sql",
  registry: "packages/db/src/mariadb/transaction-lock.registry.json",
};
const callers = [
  ["apps/operator-cli/src/operator-auth.ts", "OPERATOR_LIFECYCLE_LOCK_NAME", "shared"],
  ["apps/operator-cli/src/operator-bootstrap.ts", null, "exclusive"],
  ["apps/operator-cli/src/meal-import.ts", "IMPORT_LOCK_NAME", "try"],
  ["apps/operator-cli/src/neis-meal-sync.ts", "IMPORT_LOCK_NAME", "try"],
  ["apps/operator-cli/src/school-import.ts", "IMPORT_LOCK_NAME", "try"],
  ["apps/operator-cli/src/neis-school-schedule-sync.ts", "IMPORT_LOCK_NAME", "try"],
  ["apps/operator-cli/src/kasi-holiday-sync.ts", "IMPORT_LOCK_NAME", "try"],
];
export const transactionLockKeysSources = [
  transactionLockKeysFiles.registry,
  ...callers.map(([path]) => path),
];
const expectedIdentities = [
  "classhub:operator-lifecycle",
  "classhub:meal-import",
  "classhub:school-import",
  "classhub:school-schedule-import",
  "classhub:public-holiday-import",
];
const domain = "classhub:mariadb:transaction-lock:v1:pg-hashtextextended:0";

/** Reads source files and renders candidate DDL only; never opens a database. */
export function buildTransactionLockKeysCandidate(read = readRepository) {
  const registry = JSON.parse(read(transactionLockKeysFiles.registry));
  assert.deepEqual(
    registry,
    {
      schemaVersion: 1,
      sourceAlgorithm: "pg_hashtextextended",
      sourceSeed: "0",
      encoding: "utf8",
      digestDomain: domain,
      identities: expectedIdentities,
    },
    "transaction lock registry changed outside the five reviewed keys",
  );
  const sourceIdentities = [];
  for (const [path, constant, mode] of callers) {
    const source = read(path).replaceAll("\r\n", "\n");
    const identity = constant
      ? new RegExp(`^const ${constant} = "([^"]+)";$`, "mu").exec(source)?.[1]
      : /pg_advisory_xact_lock\(hashtextextended\('([^']+)', 0\)\)/u.exec(source)?.[1];
    assert.ok(expectedIdentities.includes(identity), `unreviewed source identity: ${path}`);
    const primitive =
      mode === "shared"
        ? "pg_advisory_xact_lock_shared"
        : mode === "try"
          ? "pg_try_advisory_xact_lock"
          : "pg_advisory_xact_lock";
    if (constant)
      assert.match(
        source,
        new RegExp(`${primitive}\\(\\s*hashtextextended\\(\\$\\{${constant}\\}, 0\\)\\s*\\)`, "u"),
        `source lock algorithm/seed/mode changed: ${path}`,
      );
    sourceIdentities.push(identity);
  }
  assert.deepEqual(
    sourceIdentities,
    [
      expectedIdentities[0],
      expectedIdentities[0],
      expectedIdentities[1],
      expectedIdentities[1],
      ...expectedIdentities.slice(2),
    ],
    "shared/exclusive or import contention identity changed",
  );
  const digests = expectedIdentities.map((identity) =>
    createHash("sha256").update(domain, "utf8").update("\0").update(identity, "utf8").digest("hex"),
  );
  assert.equal(new Set(digests).size, 5);
  const migrationSql = [
    "-- T-HUB-64: pre-registered transaction lock keys; REVIEW CANDIDATE ONLY.",
    "-- ISOLATED SYNTHETIC QA ONLY. DO NOT APPLY TO A SHARED OR PRODUCTION DATABASE.",
    "-- runtimeActivationApplied=false; existing manifests/mounts/grants remain unchanged.",
    "-- Generated by db/mariadb/verification/0032_transaction_lock_keys_candidate.mjs --write.",
    "-- Five static pg_hashtextextended(seed=0) identities; only domain-separated SHA-256 digests persist.",
    "-- Runtime candidate needs SELECT only. Installer commits seeds before any caller starts.",
    "-- Never INSERT/UPDATE/DELETE these rows in an application transaction or apply retention/TTL.",
    "-- Dynamic identities, pg_hashtext and direct-bigint key spaces are not implemented here.",
    "",
    "CREATE TABLE transaction_lock_keys (",
    "  lock_digest BINARY(32) NOT NULL,",
    "  PRIMARY KEY (lock_digest)",
    ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;",
    "",
    "START TRANSACTION;",
    "INSERT INTO transaction_lock_keys (lock_digest) VALUES",
    digests
      .map((digest, index) => `  (0x${digest})${index === digests.length - 1 ? ";" : ","}`)
      .join("\n"),
    "COMMIT;",
    "",
  ].join("\n");
  for (const identity of expectedIdentities) assert.ok(!migrationSql.includes(identity));
  return { migrationSql, digests };
}

export function verifyTransactionLockKeysCandidate(read = readRepository) {
  const candidate = buildTransactionLockKeysCandidate(read);
  assert.equal(
    read(transactionLockKeysFiles.migration).replaceAll("\r\n", "\n"),
    candidate.migrationSql,
    "0032 candidate differs from reviewed DDL and exact five seeds",
  );
  return {
    status: "transaction_lock_keys_candidate_pass",
    registeredKeys: 5,
    sourceCallers: 7,
    runtimeActivationApplied: false,
    genericDynamicIdentitySupport: false,
    realMariaDbVerified: false,
    migrationSha256: createHash("sha256").update(candidate.migrationSql).digest("hex"),
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  assert.ok(
    args.length <= 1 && [undefined, "--check", "--write"].includes(args[0]),
    "only --check or explicit --write is supported",
  );
  if (args[0] === "--write")
    writeFileSync(
      resolve(root, transactionLockKeysFiles.migration),
      buildTransactionLockKeysCandidate().migrationSql,
      "utf8",
    );
  process.stdout.write(JSON.stringify(verifyTransactionLockKeysCandidate()) + "\n");
}
