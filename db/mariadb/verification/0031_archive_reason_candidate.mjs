import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL, URL } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
export const archiveReasonSources = [
  "db/mariadb/migrations/0002_class_transition_lifecycle_routines.sql",
  "apps/api/src/classes/classes.service.ts",
];
export const archiveReasonMigration = "db/mariadb/migrations/0031_archive_reason.sql";
const hash = (value) => createHash("sha256").update(value).digest("hex");
const readRepository = (path) => readFileSync(resolve(root, path), "utf8");
const normalize = (source) => source.replaceAll("\r\n", "\n");

/** Render exactly two reason literals in one routine. Does not connect or apply SQL. */
export function buildArchiveReasonCandidate(read = readRepository) {
  const sources = Object.fromEntries(archiveReasonSources.map((path) => [path, read(path)]));
  const lifecycle = normalize(sources[archiveReasonSources[0]]);
  const service = normalize(sources[archiveReasonSources[1]]);
  assert.equal(
    service.split('const archiveReason = "반 운영 종료";').length,
    2,
    "PG archive reason anchor changed",
  );
  const prefix = "CREATE DEFINER = 'classhub_routine'@'%' PROCEDURE archive_class(";
  const pieces = lifecycle.split(prefix);
  assert.equal(pieces.length, 2, "expected exactly one archive routine");
  const end = pieces[1].indexOf("\nEND//");
  assert.ok(end >= 0);
  const original = prefix + pieces[1].slice(0, end + "\nEND//".length);
  assert.equal(original.split("'반 아카이브'").length, 3, "expected two original reason literals");
  assert.equal(original.includes("'반 운영 종료'"), false);
  const changed = original
    .replace("CREATE DEFINER", "CREATE OR REPLACE DEFINER")
    .replaceAll("'반 아카이브'", "'반 운영 종료'");
  assert.equal(
    changed
      .replace("CREATE OR REPLACE DEFINER", "CREATE DEFINER")
      .replaceAll("'반 운영 종료'", "'반 아카이브'"),
    original,
  );
  const migrationSql = [
    "-- T-HUB-64: archive reason parity; REVIEW CANDIDATE ONLY.",
    "-- ISOLATED SYNTHETIC QA ONLY. DO NOT APPLY TO SHARED OR PRODUCTION DATABASES.",
    "-- Changes only two reason literals in archive_class; no parameters, grants or other routines change.",
    "-- Generated by db/mariadb/verification/0031_archive_reason_candidate.mjs --write.",
    `-- Original archive routine SHA-256: ${hash(original)}`,
    "-- Preserve the existing routine sql_mode when replacing. Runtime activation remains false.",
    "SET time_zone = '+00:00';",
    "SET NAMES utf8mb4 COLLATE utf8mb4_bin;",
    "DELIMITER //",
    changed,
    "DELIMITER ;",
    "",
  ].join("\n");
  assert.ok(migrationSql.split("\n").length < 800);
  return {
    migrationSql,
    sourceHashes: Object.fromEntries(
      Object.entries(sources).map(([path, value]) => [path, hash(value)]),
    ),
    runtimeActivationApplied: false,
  };
}

export function verifyArchiveReasonCandidate(migrationSql, read = readRepository) {
  const expected = buildArchiveReasonCandidate(read);
  assert.equal(normalize(migrationSql), expected.migrationSql, "archive reason candidate drift");
  return expected;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  assert.ok(
    process.argv.length === 2 ||
      (process.argv.length === 3 && ["--write", "--check"].includes(process.argv[2])),
  );
  const candidate = buildArchiveReasonCandidate();
  if (process.argv[2] === "--write")
    writeFileSync(resolve(root, archiveReasonMigration), candidate.migrationSql);
  verifyArchiveReasonCandidate(readRepository(archiveReasonMigration));
  process.stdout.write(
    JSON.stringify({
      status: "archive_reason_candidate_pass",
      changedRoutines: 1,
      changedReasonLiterals: 2,
      runtimeActivationApplied: false,
    }) + "\n",
  );
}
