import { describe, expect, it } from "vitest";

import { nextDeliverableAt } from "./push-quiet-hours.js";

// 한국 시간 문자열로 입력·기대값을 적는다. 2026-09-23은 수요일, 2026-09-26은 토요일.
const kst = (value: string) => new Date(`${value}+09:00`);

describe("nextDeliverableAt", () => {
  it.each([
    ["평일 등교 전", "2026-09-23T07:30:00", "2026-09-23T07:30:00"],
    ["수업 시작 직전", "2026-09-23T08:19:59", "2026-09-23T08:19:59"],
    ["수업 시작 시각", "2026-09-23T08:20:00", "2026-09-23T16:40:00"],
    ["수업 중", "2026-09-23T11:05:00", "2026-09-23T16:40:00"],
    ["하교 시각", "2026-09-23T16:40:00", "2026-09-23T16:40:00"],
    ["저녁", "2026-09-23T19:00:00", "2026-09-23T19:00:00"],
    ["밤 시작", "2026-09-23T21:00:00", "2026-09-24T07:00:00"],
    ["자정 넘어", "2026-09-24T00:30:00", "2026-09-24T07:00:00"],
    ["아침 7시 직전", "2026-09-24T06:59:00", "2026-09-24T07:00:00"],
    ["토요일 낮은 보류 없음", "2026-09-26T11:00:00", "2026-09-26T11:00:00"],
    ["일요일 밤", "2026-09-27T22:00:00", "2026-09-28T07:00:00"],
    ["금요일 밤은 토요일 아침", "2026-09-25T23:00:00", "2026-09-26T07:00:00"],
    ["월말 밤", "2026-09-30T21:30:00", "2026-10-01T07:00:00"],
  ])("%s", (_label, input, expected) => {
    expect(nextDeliverableAt(kst(input)).toISOString()).toBe(kst(expected).toISOString());
  });

  it("UTC 자정 전후(한국 오전 9시)에도 날짜를 잘못 넘기지 않는다", () => {
    expect(nextDeliverableAt(new Date("2026-09-23T00:30:00Z")).toISOString()).toBe(
      kst("2026-09-23T16:40:00").toISOString(),
    );
  });
});
